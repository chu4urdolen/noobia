"""Offline Nexus reset‑monitor analyzer.

This module provides a small utility that consumes the ``nexus-reset-monitor``
JSONL file generated by the user‑level systemd service.  The data is streamed
line‑by‑line to avoid loading the ~1.5 MB file into memory.

The output is a JSON array of *segments*.  A segment is a contiguous block of
records with the same ``boot_id``.  If the same ``boot_id`` appears again
after another ``boot_id`` the new block is treated as a *new segment* – this
behaviour matches the specification that segments should not be merged
blindly.

Each segment contains:

* ``boot_id`` – the identifier from the records.
* ``segment_index`` – 0‑based index of the segment for the given ``boot_id``.
* ``sample_count`` – number of successfully parsed records in the segment.
* ``first_ts`` – timestamp of the first record.
* ``last_ts`` – timestamp of the last record.
* ``max_gpu_watts`` – maximum GPU power draw observed in the segment.
* ``max_gpu_util`` – GPU utilisation at the sample that produced ``max_gpu_watts``.
* ``last_sample`` – the last record before the next ``boot_id`` appears.
* ``incomplete`` – ``True`` if any record in the segment was malformed or
  missing GPU data.

The module is intentionally lightweight and has no external dependencies
beyond the standard library.
"""

from __future__ import annotations

import json
import sys
from dataclasses import dataclass, field
import math
from pathlib import Path
from typing import Dict, Iterable, List, Optional

__all__ = ["Segment", "analyze_reset_monitor", "main"]


@dataclass
class Segment:
    boot_id: str
    segment_index: int
    sample_count: int = 0
    first_ts: Optional[float] = None
    last_ts: Optional[float] = None
    max_gpu_watts: Optional[float] = None
    max_gpu_util: Optional[float] = None
    last_sample: Optional[Dict] = None
    incomplete: bool = False

    def to_dict(self) -> Dict:
        return {
            "boot_id": self.boot_id,
            "segment_index": self.segment_index,
            "sample_count": self.sample_count,
            "first_ts": self.first_ts,
            "last_ts": self.last_ts,
            "max_gpu_watts": self.max_gpu_watts,
            "max_gpu_util": self.max_gpu_util,
            "last_sample": self.last_sample,
            "incomplete": self.incomplete,
        }


def _parse_gpu_info(record: Dict) -> Optional[tuple[float, float]]:
    """Return (watts, util) from a record.

    ``record['gpu']`` is expected to be a list ``[temp, watts, util, vram]``.
    The function is tolerant of missing keys, wrong types or non‑numeric
    values.  ``None`` is returned when the information cannot be extracted.
    """
    try:
        gpu = record.get("gpu", [])
        if len(gpu) < 3:
            return None
        watts = float(gpu[1])
        util = float(gpu[2])
        # Treat NaN as missing data
        if math.isnan(watts) or math.isnan(util):
            return None
        return watts, util
    except Exception:
        return None


def analyze_reset_monitor(jsonl_path: str | Path) -> List[Segment]:
    """Analyze a ``nexus-reset-monitor`` JSONL file.

    Parameters
    ----------
    jsonl_path:
        Path to the JSONL file.  The file is read in a streaming fashion.

    Returns
    -------
    List[Segment]
        One ``Segment`` instance per contiguous block of ``boot_id``.
    """
    jsonl_path = Path(jsonl_path)
    segments: List[Segment] = []
    current_seg: Optional[Segment] = None
    segment_counter: Dict[str, int] = {}

    with jsonl_path.open("r", encoding="utf-8") as fp:
        for line_no, raw in enumerate(fp, 1):
            raw = raw.strip()
            if not raw:
                continue
            try:
                record = json.loads(raw)
            except json.JSONDecodeError:
                # Malformed line – mark the current segment incomplete and skip.
                if current_seg:
                    current_seg.incomplete = True
                continue

            boot_id = record.get("boot_id")
            if boot_id is None:
                # If boot_id is missing we cannot continue the segment.
                if current_seg:
                    current_seg.incomplete = True
                continue

            if current_seg is None or current_seg.boot_id != boot_id:
                # Start a new segment.
                if current_seg:
                    segments.append(current_seg)
                idx = segment_counter.get(boot_id, 0)
                segment_counter[boot_id] = idx + 1
                current_seg = Segment(boot_id=boot_id, segment_index=idx)
                current_seg.first_ts = float(record.get("time", 0))
            # Update segment stats.
            current_seg.sample_count += 1
            ts = float(record.get("time", 0))
            current_seg.last_ts = ts
            gpu_info = _parse_gpu_info(record)
            if gpu_info is None:
                current_seg.incomplete = True
            else:
                watts, util = gpu_info
                if current_seg.max_gpu_watts is None or watts > current_seg.max_gpu_watts:
                    current_seg.max_gpu_watts = watts
                    current_seg.max_gpu_util = util
            # Keep the last sample for potential reporting.
            current_seg.last_sample = record
    # Append the final segment.
    if current_seg:
        segments.append(current_seg)
    return segments


def main(argv: List[str] | None = None) -> None:
    """CLI entry point.

    Usage: ``python -m aria.inference.analyze_reset_monitor <path>``
    The output is a JSON array written to stdout.
    """
    if argv is None:
        argv = sys.argv[1:]
    if len(argv) != 1:
        print("Usage: python -m aria.inference.analyze_reset_monitor <jsonl_path>", file=sys.stderr)
        sys.exit(1)
    jsonl_path = Path(argv[0])
    segments = analyze_reset_monitor(jsonl_path)
    print(json.dumps([s.to_dict() for s in segments], indent=2))


if __name__ == "__main__":
    main()

